const normaliser = (s = "") =>
  s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().trim();

// Retrouve le gouvernorat d'un match, même ancien (sans champ gouvernorat)
export const gouvernoratDuMatch = (m) => {
  if (m.gouvernorat) return m.gouvernorat;
  const texte = normaliser(`${m.ville || ""} ${m.terrain || ""}`);
  const trouve = GOUVERNORATS.find((g) => texte.includes(normaliser(g)));
  return trouve || "";
};

export const memeGouvernorat = (m, choix) =>
  !choix || normaliser(gouvernoratDuMatch(m)) === normaliser(choix);

// Validation de la ville choisie
export const validerCommune = (gouvernorat, commune) => {
  if (!gouvernorat) return "Choisis d'abord un gouvernorat.";
  return (VILLES[gouvernorat] || []).includes(commune) ? "" : "Choisis une ville dans la liste.";
};

// 0 = même ville, 1 = même gouvernorat, 2 = ailleurs
export const rangProximite = (lieu, moi) => {
  if (!moi?.gouvernorat) return 2;
  const memeG = normaliser(lieu.gouvernorat || "") === normaliser(moi.gouvernorat);
  if (memeG && lieu.commune && moi.commune && lieu.commune === moi.commune && lieu.commune !== "Autre") return 0;
  return memeG ? 1 : 2;
};